_NEW_DEFAULT_KEYS = {it["key"] for it in _DEFAULT_QUESTIONNAIRE_ITEMS}
_OLD_DEFAULT_MARKER_KEYS = {"occurred_at", "has_topology_diagram", "trigger_action", "event"}


def _ensure_default_questionnaire(conn: "_Conn") -> None:
    """name='default' のテンプレを新問診票 (障害状況問診票) に揃える。

    - 無ければ新問診票で作成。
    - 既存が旧デフォルト構造 (occurred_at / has_topology_diagram 等を含む) なら
      新問診票へ置き換える (2026-07 改訂。PoC 期間中の旧互換は保証しない方針)。
    - 上記以外 (利用者が独自に編集した default) は触らない。
    """
    row = conn.execute(
        "SELECT id, items_json FROM questionnaire_templates WHERE name = ?",
        (_DEFAULT_QUESTIONNAIRE_NAME,),
    ).fetchone()
    now = _now_iso()
    payload = json.dumps(_DEFAULT_QUESTIONNAIRE_ITEMS, ensure_ascii=False)
    if row is None:
        conn.execute(
            "INSERT INTO questionnaire_templates "
            "(name, description, items_json, created_at, updated_at) VALUES (?, ?, ?, ?, ?)",
            (_DEFAULT_QUESTIONNAIRE_NAME, "障害状況問診票", payload, now, now),
        )
        return
    raw_items = row["items_json"]
    try:
        items = json.loads(raw_items) if raw_items else []
    except Exception:  # noqa: BLE001
        items = []
    keys = {it.get("key") for it in items if isinstance(it, dict)}
    if keys == _NEW_DEFAULT_KEYS:
        return  # 既に新問診票
    # 旧デフォルト構造なら新問診票へアップグレード
    if keys & _OLD_DEFAULT_MARKER_KEYS:
        conn.execute(
            "UPDATE questionnaire_templates SET items_json = ?, description = ?, updated_at = ? "
            "WHERE id = ?",
            (payload, "障害状況問診票", now, row["id"]),
        )


@contextmanager
def _connect() -> Iterator["_Conn"]:
    if _BACKEND == "postgres":
        # pool.connection() は正常終了で commit / 例外で rollback してから返却する。
        with _get_pool().connection() as raw:
            yield _Conn(raw, "postgres")
        return
    _ensure_dir()
    raw = sqlite3.connect(_DB_PATH)
    raw.row_factory = sqlite3.Row
    try:
        yield _Conn(raw, "sqlite")
    finally:
        raw.close()


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _row_to_config(row: Any) -> dict:
    d = dict(row)
    raw_p = d.pop("overrides_json")
    raw_m = d.pop("model_overrides_json", None)
    raw_pipe = d.pop("pipeline_json", None)
    d["overrides"] = json.loads(raw_p) if raw_p else {}
    d["model_overrides"] = json.loads(raw_m) if raw_m else {}
    d["pipeline"] = json.loads(raw_pipe) if raw_pipe and raw_pipe != "{}" else None
    return d


_COLS = (
    "id, name, base_config, overrides_json, model_overrides_json, pipeline_json, "
    "created_at, updated_at"
)


def list_saved_configs() -> list[dict]:
    with _connect() as conn:
        rows = conn.execute(
            f"SELECT {_COLS} FROM saved_configs ORDER BY updated_at DESC"
        ).fetchall()
    return [_row_to_config(r) for r in rows]


def get_saved_config(config_id: int) -> dict | None:
    with _connect() as conn:
        row = conn.execute(
            f"SELECT {_COLS} FROM saved_configs WHERE id = ?",
            (config_id,),
        ).fetchone()
    return _row_to_config(row) if row else None


def create_saved_config(
    name: str,
    base_config: str,
    overrides: dict[str, str],
    model_overrides: dict[str, str] | None = None,
    pipeline: dict | None = None,
) -> dict:
    now = _now_iso()
    p = json.dumps(overrides, ensure_ascii=False)
    m = json.dumps(model_overrides or {}, ensure_ascii=False)
    pipe = json.dumps(pipeline or {}, ensure_ascii=False) if pipeline else "{}"
    with _connect() as conn:
        config_id = _insert_returning_id(
            conn,
            "INSERT INTO saved_configs (name, base_config, overrides_json, model_overrides_json, "
            "pipeline_json, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?)",
            (name, base_config, p, m, pipe, now, now),
        )
        conn.commit()
    saved = get_saved_config(config_id) if config_id else None
    if saved is None:
        raise RuntimeError("failed to retrieve saved config after insert")
    return saved


def update_saved_config(
    config_id: int,
    overrides: dict[str, str],
    model_overrides: dict[str, str] | None = None,
    pipeline: dict | None = None,
) -> dict | None:
    now = _now_iso()
    p = json.dumps(overrides, ensure_ascii=False)
    m = json.dumps(model_overrides or {}, ensure_ascii=False)
    pipe = json.dumps(pipeline or {}, ensure_ascii=False) if pipeline else "{}"
    with _connect() as conn:
        cursor = conn.execute(
            "UPDATE saved_configs SET overrides_json = ?, model_overrides_json = ?, "
            "pipeline_json = ?, updated_at = ? WHERE id = ?",
            (p, m, pipe, now, config_id),
        )
        conn.commit()
        if cursor.rowcount == 0:
            return None
    return get_saved_config(config_id)


def delete_saved_config(config_id: int) -> bool:
    with _connect() as conn:
        cursor = conn.execute("DELETE FROM saved_configs WHERE id = ?", (config_id,))
        conn.commit()
        return cursor.rowcount > 0


