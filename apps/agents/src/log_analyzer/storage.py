def insert_analysis_history(
    *,
    run_id: str,
    kind: str,
    config_id: str,
    analysis_mode: str | None,
    single_source: str | None,
    stage_order: str | None,
    title: str | None,
    confidence: float | None,
    tokens_in: int | None,
    tokens_out: int | None,
    latency_ms: int | None,
    top_category: str | None,
    top_summary: str | None,
    trace_id: str | None,
    request_json: str,
    result_json: str,
    created_at: str | None = None,
) -> tuple[int, bool]:
    """解析履歴を 1 件保存し、``(id, created)`` を返す。

    同一 ``run_id`` が既にあれば挿入せず ``created=False`` と既存 id を返す (no-op)。
    """
    with _connect() as conn:
        existing = conn.execute(
            "SELECT id FROM analysis_history WHERE run_id = ?", (run_id,)
        ).fetchone()
        if existing is not None:
            return int(existing["id"]), False
        when = created_at or _now_iso()
        new_id = _insert_returning_id(
            conn,
            "INSERT INTO analysis_history "
            "(run_id, created_at, kind, config_id, analysis_mode, single_source, stage_order, "
            " title, confidence, tokens_in, tokens_out, latency_ms, top_category, top_summary, "
            " trace_id, request_json, result_json) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            (
                run_id, when, kind, config_id, analysis_mode, single_source, stage_order,
                title, confidence, tokens_in, tokens_out, latency_ms, top_category, top_summary,
                trace_id, request_json, result_json,
            ),
        )
        conn.commit()
        return new_id, True


def list_analysis_history(
    *,
    kind: str | None = None,
    analysis_mode: str | None = None,
    q: str | None = None,
    limit: int = 200,
    offset: int = 0,
) -> tuple[list[dict], int]:
    """フィルタ付きで一覧（サマリのみ）を返す。``(rows, total_count)``。"""
    where: list[str] = []
    args: list = []
    if kind:
        where.append("kind = ?")
        args.append(kind)
    if analysis_mode:
        where.append("analysis_mode = ?")
        args.append(analysis_mode)
    if q:
        # top_summary / title に加え、解析結果本体 (result_json) も対象にする。
        # 候補 summary / evidence / 委譲理由などは result_json 内にしか無いため、
        # ここを含めないと本文テキストで検索してもヒットしない。
        where.append("(top_summary LIKE ? OR title LIKE ? OR result_json LIKE ?)")
        like = f"%{q}%"
        args.extend([like, like, like])
    where_sql = (" WHERE " + " AND ".join(where)) if where else ""
    with _connect() as conn:
        total = conn.execute(
            f"SELECT COUNT(*) AS n FROM analysis_history{where_sql}", args
        ).fetchone()["n"]
        rows = conn.execute(
            f"SELECT {_ANALYSIS_SUMMARY_COLS} FROM analysis_history{where_sql} "
            f"ORDER BY created_at DESC LIMIT ? OFFSET ?",
            (*args, limit, offset),
        ).fetchall()
    return [dict(r) for r in rows], int(total)


