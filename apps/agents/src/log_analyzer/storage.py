# ─── analysis_evaluations (解析レポート × 解答 の評価結果) ──────────

_EVAL_COLS = (
    "id, analysis_history_id, scenario_key, score, axis_assessment_json, good_points_json, "
    "bad_points_json, pitfalls_avoided_json, pitfalls_hit_json, summary, model, tokens_in, "
    "tokens_out, latency_ms, created_at"
)
_EVAL_LIST_FIELDS = (
    "axis_assessment", "good_points", "bad_points", "pitfalls_avoided", "pitfalls_hit",
)


def _row_to_evaluation(row: Any) -> dict:
    d = dict(row)
    for f in _EVAL_LIST_FIELDS:
        raw = d.pop(f"{f}_json", None)
        try:
            d[f] = json.loads(raw) if raw else []
        except Exception:  # noqa: BLE001
            d[f] = []
    return d


def insert_evaluation(
    *,
    analysis_history_id: int,
    scenario_key: str,
    score: int | None,
    axis_assessment: list[str],
    good_points: list[str],
    bad_points: list[str],
    pitfalls_avoided: list[str],
    pitfalls_hit: list[str],
    summary: str,
    model: str,
    tokens_in: int | None = None,
    tokens_out: int | None = None,
    latency_ms: int | None = None,
) -> dict:
    """評価を 1 件保存し、保存後の行 (リストはパース済み) を返す。"""
    now = _now_iso()

    def _j(v: list[str]) -> str:
        return json.dumps([str(x) for x in (v or [])], ensure_ascii=False)

    with _connect() as conn:
        eval_id = _insert_returning_id(
            conn,
            "INSERT INTO analysis_evaluations "
            "(analysis_history_id, scenario_key, score, axis_assessment_json, good_points_json, "
            " bad_points_json, pitfalls_avoided_json, pitfalls_hit_json, summary, model, "
            " tokens_in, tokens_out, latency_ms, created_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            (
                analysis_history_id, str(scenario_key), score, _j(axis_assessment),
                _j(good_points), _j(bad_points), _j(pitfalls_avoided), _j(pitfalls_hit),
                summary, model, tokens_in, tokens_out, latency_ms, now,
            ),
        )
        conn.commit()
    saved = get_evaluation(eval_id)
    if saved is None:
        raise RuntimeError("failed to retrieve evaluation after insert")
    return saved


def get_evaluation(eval_id: int) -> dict | None:
    with _connect() as conn:
        row = conn.execute(
            f"SELECT {_EVAL_COLS} FROM analysis_evaluations WHERE id = ?", (eval_id,)
        ).fetchone()
    return _row_to_evaluation(row) if row else None


