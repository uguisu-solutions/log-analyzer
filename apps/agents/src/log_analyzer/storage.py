# psycopg のコネクションプール（postgres 時のみ遅延生成）
_pool: Any = None


def _ensure_dir() -> None:
    if _BACKEND == "sqlite":
        _DB_PATH.parent.mkdir(parents=True, exist_ok=True)


def _to_pg(sql: str) -> str:
    """SQLite 方言で書いた SQL を psycopg（PostgreSQL）用に変換する。

    - ``INTEGER PRIMARY KEY AUTOINCREMENT`` → IDENTITY 列（DDL）
    - 名前付き ``:name`` → ``%(name)s``
    - 位置 ``?`` → ``%s``
    - ``LIKE`` → ``ILIKE``（SQLite の LIKE は ASCII 大小無視なので挙動を揃える）

    対象 SQL には ``?`` / ``:name`` 以外のリテラル ``?`` や ``%`` を含めない前提
    （本モジュール内の SQL はこれを満たす）。
    """
    sql = sql.replace(
        "INTEGER PRIMARY KEY AUTOINCREMENT",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    )
    sql = re.sub(r":(\w+)", r"%(\1)s", sql)
    sql = sql.replace("?", "%s")
    sql = re.sub(r"\bLIKE\b", "ILIKE", sql)
    return sql


class _Conn:
    """sqlite3.Connection / psycopg.Connection の差を吸収する薄いラッパ。

    ``execute(sql, params)`` は cursor 相当を返し、``.fetchone()`` /
    ``.fetchall()`` / ``.rowcount`` / ``.lastrowid``（SQLite のみ）が使える。
    行は SQLite=``sqlite3.Row`` / PostgreSQL=``dict_row`` で、いずれも
    ``dict(row)`` と ``row["col"]`` が使える（``row[int]`` は SQLite のみ）。
    """

    def __init__(self, raw: Any, backend: str) -> None:
        self._raw = raw
        self.backend = backend

    def execute(self, sql: str, params: Any = ()):  # noqa: ANN401
        if self.backend == "postgres":
            return self._raw.execute(_to_pg(sql), params)
        return self._raw.execute(sql, params)

    def commit(self) -> None:
        self._raw.commit()


def _get_pool() -> Any:
    """PostgreSQL コネクションプールを遅延生成して返す（Supabase pooler 等対応）。"""
    global _pool
    if _pool is None:
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool

        _pool = ConnectionPool(
            _DATABASE_URL,
            kwargs={"row_factory": dict_row},
            min_size=1,
            max_size=int(os.environ.get("DB_POOL_MAX", "10")),
            open=False,
        )
        _pool.open()
    return _pool


def _table_columns(conn: "_Conn", table: str) -> set[str]:
    """テーブルの列名集合を返す（存在しなければ空集合）。マイグレーション判定用。"""
    if conn.backend == "postgres":
        rows = conn.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_name = ?",
            (table,),
        ).fetchall()
        return {r["column_name"] for r in rows}
    rows = conn.execute(f"PRAGMA table_info({table})").fetchall()
    return {r[1] for r in rows}


def _insert_returning_id(conn: "_Conn", sql: str, params: Any) -> int:  # noqa: ANN401
    """INSERT を実行し、生成された id を返す（lastrowid / RETURNING の差を吸収）。"""
    if conn.backend == "postgres":
        row = conn.execute(sql + " RETURNING id", params).fetchone()
        return int(row["id"]) if row else 0
    cur = conn.execute(sql, params)
    return int(cur.lastrowid or 0)


